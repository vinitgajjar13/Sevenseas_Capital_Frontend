export const exportRadarToCSV = (stocks: StockRadarItem[]) => {
  const headers = [
    'Rank',
    'Symbol',
    'Company Name',
    'Sector',
    'Slot',
    'Status',
    'Action',
    'Quant Score',
    'LTP (₹)',
    'Change %',
    'VWAP',
    '9:15 High',
    '9:15 Low',
    'RVol',
    'RSI',
    'Breakout Status',
    'Target 1',
    'Target 2',
    'Stop Loss',
  ];

  const rows = stocks.map((s) => [
    s.rank,
    s.symbol,
    `"${s.name}"`,
    `"${s.sector}"`,
    `"${s.slot}"`,
    s.status,
    `"${s.action}"`,
    s.score,
    s.ltp,
    `${s.changePercent}%`,
    s.vwap,
    s.high915,
    s.low915,
    `${s.rvol}x`,
    s.rsi,
    s.breakoutType,
    s.target1,
    s.target2,
    s.stopLoss,
  ]);

  const csvContent = 'data:text/csv;charset=utf-8,' + [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
  const encodedUri = encodeURI(csvContent);
  const link = document.createElement('a');
  link.setAttribute('href', encodedUri);
  link.setAttribute('download', `NSE_Stock_Radar_Export_${new Date().toISOString().slice(0, 10)}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
};
